// Export a saved script as a standalone Playwright Test spec (@playwright/test).
const q = (s) => JSON.stringify(String(s ?? ''));

function locator(t) {
  if (!t) return 'page';
  // ids, test ids and name attributes are the most stable; positional CSS paths the least.
  if (t.css && /^(#|\[data-|[a-z]+\[name=)/i.test(t.css)) return `page.locator(${q(t.css)})`;
  // Not exact: accessible names can include icon-font glyphs that innerText (and the snapshot) never sees.
  if (t.role && t.name) return `page.getByRole(${q(t.role)}, { name: ${q(t.name)} })`;
  if (t.label) return `page.getByLabel(${q(t.label)})`;
  if (t.placeholder) return `page.getByPlaceholder(${q(t.placeholder)})`;
  if (t.css) return `page.locator(${q(t.css)})`;
  if (t.text) return `page.getByText(${q(t.text)}, { exact: true })`;
  return 'page';
}

const reEsc = (s) => String(s).replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');

function line(step, baseUrl) {
  const l = locator(step.target);
  const v = step.value ?? '';
  switch (step.action) {
    case 'goto': return `await page.goto(${q(new URL(v || baseUrl, baseUrl).toString())}, { waitUntil: 'domcontentloaded' });`;
    case 'back': return 'await page.goBack();';
    case 'click': return `await ${l}.click();`;
    case 'fill': return `await ${l}.fill(${q(v)});`;
    case 'select': return `await ${l}.selectOption({ label: ${q(v)} });`;
    case 'check': return `await ${l}.check();`;
    case 'uncheck': return `await ${l}.uncheck();`;
    case 'hover': return `await ${l}.hover();`;
    case 'press': return step.target ? `await ${l}.press(${q(v || 'Enter')});` : `await page.keyboard.press(${q(v || 'Enter')});`;
    case 'scroll': return step.target ? `await ${l}.scrollIntoViewIfNeeded();` : `await page.mouse.wheel(0, ${/up/i.test(v) ? -600 : 600});`;
    case 'wait': return `await page.waitForTimeout(${Number(v) || 1000});`;
    case 'assert_text': return `await expect(page.locator('body')).toContainText(${q(v)}, { ignoreCase: true, timeout: 15_000 });`;
    case 'assert_no_text': return `await expect(page.locator('body')).not.toContainText(${q(v)}, { ignoreCase: true, timeout: 15_000 });`;
    case 'assert_url': return `await expect(page).toHaveURL(/${reEsc(v)}/i, { timeout: 15_000 });`;
    case 'assert_title': return `await expect(page).toHaveTitle(/${reEsc(v)}/i, { timeout: 15_000 });`;
    case 'assert_visible': return `await expect(${l}).toBeVisible({ timeout: 15_000 });`;
    default: return `// unsupported step: ${JSON.stringify(step)}`;
  }
}

export function toPlaywrightSpec(script) {
  const out = [
    `// Generated by AI QA Tester from script "${script.name}"`,
    '// Run with: npx playwright test',
    "import { test, expect } from '@playwright/test';",
    '',
    `test.describe(${q(script.name)}, () => {`,
    '  // Real sites can be slow; the default 30 s per test is often too tight for end-to-end flows.',
    '  test.describe.configure({ timeout: 120_000 });',
    '',
  ];
  for (const t of script.tests) {
    out.push(`  test(${q(t.title)}, async ({ page }) => {`);
    const steps = t.steps[0]?.action === 'goto' ? t.steps : [{ action: 'goto', value: script.url }, ...t.steps];
    for (const s of steps) out.push(`    ${line(s, script.url)}`);
    out.push('  });', '');
  }
  out.push('});', '');
  return out.join('\n');
}
